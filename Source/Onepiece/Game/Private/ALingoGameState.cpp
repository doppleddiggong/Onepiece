ALingoGameState::ALingoGameState()
{
	RemainMissionTime = 0.f;
	bIsTimerActive = false;

	PrimaryActorTick.bCanEverTick = true;

	// RoomId, RoomLevel은  Host가 생성합니다
	RoomId = 0;
	RoomLevel = 1;

	Bot.id = DefineData::BotID;
	Bot.username = DefineData::BotName;
	Bot.fullname = DefineData::BotName;
	Bot.is_active = true;

	Bot.my_avatar = TEXT("[BOT]");
	Bot.my_color = TEXT("[BOT]");
}

