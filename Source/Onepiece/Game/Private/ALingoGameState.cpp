void ALingoGameState::SetRoomLevel(int32 InRoomLevel)
{
	// 서버에서만 실행
	if (!HasAuthority())
	{
		PRINTLOG(TEXT("[SetRoomLevel] Failed: Not authority"));
		return;
	}

	RoomLevel = InRoomLevel;
	PRINTLOG(TEXT("[SetRoomLevel] RoomLevel set to %d"), RoomLevel);

	// 서버(Host)는 OnRep가 호출되지 않으므로 직접 델리게이트 브로드캐스트
	// 클라이언트는 Replication으로 인해 OnRep_RoomLevel이 호출되어 델리게이트가 브로드캐스트됨
	OnRoomLevelUpdated.Broadcast(RoomLevel);
}

void ALingoGameState::StartMissionTimer(float InTimeLimit)
{
	// 서버에서만 실행
	if (!HasAuthority())
		return;

	this->TimeLimit = InTimeLimit;
	this->RemainMissionTime = InTimeLimit;
	this->bIsTimerActive = true;

	if (ANetworkBroadcastActor* BroadcastActor = ANetworkBroadcastActor::Get(this))
		BroadcastActor->SendUpdateMissionTimerState(true, InTimeLimit, this);
}

void ALingoGameState::StopMissionTimer()
{
	if (!HasAuthority())
		return;

	bIsTimerActive = false;

	// NetworkBroadcastActor를 통해 모든 클라이언트에 타이머 중지 알림
	if (ANetworkBroadcastActor* BroadcastActor = ANetworkBroadcastActor::Get(this))
	{
		BroadcastActor->SendUpdateMissionTimerState(false, 0.0f, this);
	}
}

void ALingoGameState::DecreaseMissionTimer(const float InValue)
{
	this->RemainMissionTime = FMath::Max(0.f, RemainMissionTime - InValue);
}

void ALingoGameState::UpdateRemainMissionTime(const float InTimeLimit)
{
	this->TimeLimit = InTimeLimit;
	this->RemainMissionTime = InTimeLimit;
}

void ALingoGameState::OnMissionTimerEnd()
{
	if (!HasAuthority())
		return;

	bIsTimerActive = false;

	// NetworkBroadcastActor를 통해 모든 클라이언트에 타이머 종료 알림
	if (ANetworkBroadcastActor* BroadcastActor = ANetworkBroadcastActor::Get(this))
		BroadcastActor->SendUpdateMissionTimerState(false, 0.0f, this);

	auto EndMessage = ULingoGameHelper::GetStageEndMessage(QuestType);

	PRINTLOG( TEXT("[GameState] Mission Timer Ended - Sending: %s"), *EndMessage);

	// Read, Listen Quest일 때 자동으로 결과 팝업 표시
	if (QuestType == EQuestType::Read || QuestType == EQuestType::Listen)
	{
		if (auto Popup = UPopupManager::ShowPopupAs<UPopup_Result>(GetWorld(), EPopupType::Result))
		{
			Popup->InitPopup(QuestType);
		}
	}

	// 모든 플레이어에게 메시지 전송
	if (UWorld* World = GetWorld())
	{
		for (FConstPlayerControllerIterator It = World->GetPlayerControllerIterator(); It; ++It)
		{
			if (APlayerController* PC = It->Get())
			{
				if (APlayerActor* PlayerActor = Cast<APlayerActor>(PC->GetPawn()))
				{
					PlayerActor->OnGameMessage(EndMessage);
				}
			}
		}
	}
}


void ALingoGameState::Multicast_UpdateQuestType_Implementation(const EQuestType InQuestType)
{
	// 0.5초 딜레이 후 팝업 표시
	if (UWorld* World = GetWorld())
	{
		FTimerHandle TimerHandle;
		World->GetTimerManager().SetTimer(TimerHandle, [this, InQuestType]()
		{
			OnQuestScenarioDataUpdated.Broadcast();
		}, 0.5f, false);
	}
}


